/** "oil 1871:1 1901:10; gas 1950:2" -> [["oil", [[1871, 1], [1901, 10]]], ["gas", [[1950, 2]]]]. */
export function parseResources(spec) {
  return spec.split(";").map((part) => {
    const [type, ...points] = part.trim().split(/\s+/);
    if (!RESOURCE_TYPES.includes(type)) throw new Error(`Unknown resource type: ${type}`);
    const curve = points.map((p) => p.split(":").map(Number));
    if (!curve.length || curve.some(([y, v]) => !Number.isFinite(y) || !Number.isFinite(v))) throw new Error(`Bad checkpoints: ${part}`);
    return [type, curve.sort((a, b) => a[0] - b[0])];
  });
}
