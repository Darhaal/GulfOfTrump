export function riverName(raw: string, locale: Locale): string {
  // Natural Earth writes a few names with a double space ("Syr  Darya").
  const name = raw.replace(/\s+/g, " ").trim();
  const row = RIVERS[name];
  if (!row || locale === "en") return name;
  return locale === "ru" ? row[0] : row[1];
}
