/** Whether the interface can show this leader in Russian and Ukrainian. */
export const hasLeaderName = (leader: string) => leader in LEADERS;

/** A leader as the interface shows it in this language. */
export function leaderName(leader: string, locale: Locale): string {
  const known = LEADERS[leader];
  if (!known || locale === "en") return leader;
  return locale === "ru" ? known[0] : known[1];
}
